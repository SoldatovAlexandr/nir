package edu.asoldatov.nir.model.types;

import lombok.AllArgsConstructor;
import lombok.Getter;

@Getter
@AllArgsConstructor
public enum Difficulties {

    NONE("Трудности отсутвуют"),
    NO("Затрудняюсь ответить"),
    TIME("Отсутвие времени на лечение"),
    LOAD("Загурженность врача-стоматолога (длинная очередь, )"),
    AFRAID("Страх лечения (возможная боль, недоверие к врачу, неэфективонсти анесезии)"),
    OBO("Изношеннсть оборуждования"),
    BOL("Страх лечения из-за боли"),
    VID("Отсутвие другого вида помощи (ортодонтической, хирургической)"),
    LECH("Осбенности лечения (сложная клиническая ситуация, аллергиеские реакции, физиологиеские особенности)");

    private final String label;
}
